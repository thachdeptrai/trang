alter table public.wishes
  add column if not exists category varchar(16) not null default 'other',
  add column if not exists lantern_color varchar(16) not null default 'amber',
  add column if not exists lantern_style text not null default 'classic';

alter table public.wishes drop constraint if exists wishes_category_check;
alter table public.wishes
  add constraint wishes_category_check
  check (category in ('family','health','love','dream','luck','other'));

alter table public.wishes drop constraint if exists wishes_lantern_color_check;
alter table public.wishes
  add constraint wishes_lantern_color_check
  check (lantern_color in ('amber','red','jade','blue','violet'));

alter table public.wishes drop constraint if exists wishes_lantern_style_check;

update public.wishes
set lantern_style = case lantern_style
  when 'jade' then 'round'
  when 'rose' then 'lotus'
  when 'violet' then 'diamond'
  when 'blue' then 'tower'
  when 'amber' then 'classic'
  else lantern_style
end
where lantern_style in ('amber','jade','rose','violet','blue');

alter table public.wishes
  alter column lantern_style set default 'classic';

alter table public.wishes
  add constraint wishes_lantern_style_check
  check (lantern_style in ('classic','round','lotus','diamond','tower'));

create index if not exists wishes_category_created_at_idx
  on public.wishes (category, created_at desc);

