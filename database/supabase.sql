drop view if exists public.wish_feed;
create view public.wish_feed
with (security_invoker = true)
as
select
  w.id,
  w.name,
  w.message,
  w.created_at,
  w.category,
  w.lantern_color,
  w.lantern_style,
  lower(w.name || ' ' || w.message) as search_text,
  coalesce(r.heart_count,0)::bigint as heart_count,
  coalesce(r.star_count,0)::bigint as star_count,
  coalesce(r.moon_count,0)::bigint as moon_count,
  coalesce(l.light_count,0)::bigint as light_count,
  (
    coalesce(r.heart_count,0)
    + coalesce(r.star_count,0)
    + coalesce(r.moon_count,0)
    + coalesce(l.light_count,0) * 2
  )::bigint as activity_score
from public.wishes w
left join (
  select
    wish_id,
    count(*) filter (where reaction='heart')::bigint as heart_count,
    count(*) filter (where reaction='star')::bigint as star_count,
    count(*) filter (where reaction='moon')::bigint as moon_count
  from public.wish_reactions
  group by wish_id
) r on r.wish_id = w.id
left join (
  select wish_id, count(*)::bigint as light_count
  from public.wish_lights
  group by wish_id
) l on l.wish_id = w.id;

grant select on public.wish_feed to anon, authenticated;

create table if not exists public.wish_reports (
  id bigint generated by default as identity primary key,
  wish_id bigint not null references public.wishes(id) on delete cascade,
  reporter_id uuid not null,
  reason varchar(32) not null default 'other',
  detail varchar(240),
  created_at timestamptz not null default now(),
  constraint wish_reports_reason_check
    check (reason in ('spam','abuse','personal_info','other')),
  constraint wish_reports_detail_length
    check (detail is null or char_length(btrim(detail)) <= 240),
  unique (wish_id, reporter_id)
);

alter table public.wish_reports enable row level security;

revoke all on table public.wish_reports from anon, authenticated;
grant insert on table public.wish_reports to anon, authenticated;
grant usage, select on sequence public.wish_reports_id_seq to anon, authenticated;

drop policy if exists "public can report a wish once" on public.wish_reports;
create policy "public can report a wish once"
on public.wish_reports
for insert
to anon, authenticated
with check (
  reporter_id is not null
  and reason in ('spam','abuse','personal_info','other')
  and (detail is null or char_length(btrim(detail)) <= 240)
);

comment on view public.wish_feed is
  'RLS-aware public aggregate feed for TRANG V4.';

comment on table public.wish_lights is
  'One public light per visitor per wish.';

comment on table public.wish_reports is
  'Public write-only moderation reports for wishes.';
