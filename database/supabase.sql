-- TRĂNG / public wishes database
-- Run this once in Supabase SQL Editor.
-- Public visitors may only SELECT and INSERT wishes. UPDATE/DELETE stay blocked.

create table if not exists public.wishes (
  id bigint generated by default as identity primary key,
  name varchar(40) not null,
  message varchar(180) not null,
  created_at timestamptz not null default now(),
  constraint wishes_name_length check (char_length(btrim(name)) between 1 and 40),
  constraint wishes_message_length check (char_length(btrim(message)) between 1 and 180)
);

create index if not exists wishes_created_at_idx
  on public.wishes (created_at desc);

alter table public.wishes enable row level security;

revoke all on table public.wishes from anon, authenticated;
grant select, insert on table public.wishes to anon, authenticated;
grant usage, select on sequence public.wishes_id_seq to anon, authenticated;

drop policy if exists "public can read wishes" on public.wishes;
create policy "public can read wishes"
on public.wishes
for select
to anon, authenticated
using (true);

drop policy if exists "public can submit wishes" on public.wishes;
create policy "public can submit wishes"
on public.wishes
for insert
to anon, authenticated
with check (
  char_length(btrim(name)) between 1 and 40
  and char_length(btrim(message)) between 1 and 180
);

-- Realtime: add the table to Supabase Realtime publication.
do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'wishes'
  ) then
    alter publication supabase_realtime add table public.wishes;
  end if;
end $$;

comment on table public.wishes is
  'Public, non-sensitive Mid-Autumn wishes displayed on the TRANG website.';


-- V3: public reactions for wishes.
create table if not exists public.wish_reactions (
  id bigint generated by default as identity primary key,
  wish_id bigint not null references public.wishes(id) on delete cascade,
  client_id uuid not null,
  reaction text not null check (reaction in ('heart','star','moon')),
  created_at timestamptz not null default now(),
  unique (wish_id, client_id, reaction)
);

create index if not exists wish_reactions_wish_id_idx
  on public.wish_reactions (wish_id);

alter table public.wish_reactions enable row level security;

revoke all on table public.wish_reactions from anon, authenticated;
grant select, insert on table public.wish_reactions to anon, authenticated;
grant usage, select on sequence public.wish_reactions_id_seq to anon, authenticated;

drop policy if exists "public can read reactions" on public.wish_reactions;
create policy "public can read reactions"
on public.wish_reactions
for select
to anon, authenticated
using (true);

drop policy if exists "public can add reactions" on public.wish_reactions;
create policy "public can add reactions"
on public.wish_reactions
for insert
to anon, authenticated
with check (reaction in ('heart','star','moon'));

do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'wish_reactions'
  ) then
    alter publication supabase_realtime add table public.wish_reactions;
  end if;
end $$;

comment on table public.wish_reactions is
  'Public reactions for Mid-Autumn wishes. Anonymous clients may read and insert only.';
